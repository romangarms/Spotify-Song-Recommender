@generation_bp.route("/search/tracks", methods=["GET"])
def search_tracks():
    """
    Search Spotify for tracks to seed a playlist.

    Query Parameters:
        q: Search query
        limit: Max results (capped at SEARCH_MAX_LIMIT)

    Returns:
        JSON: { tracks: [...], query: str, count: int }
    """
    query = request.args.get("q", "").strip()

    if len(query) < 2:
        return jsonify({
            "error": "invalid_query",
            "message": "Query must be at least 2 characters"
        }), 400

    try:
        limit = min(int(request.args.get("limit", SEARCH_MAX_LIMIT)), SEARCH_MAX_LIMIT)
    except ValueError:
        limit = SEARCH_MAX_LIMIT

    try:
        results = get_public_spotify().search(q=query, type="track", limit=limit)

        tracks = []
        # Spotify returns null entries for items the app can't access.
        for item in filter(None, results["tracks"]["items"]):
            album = item.get("album") or {}
            tracks.append({
                "id": item["id"],
                "name": item["name"],
                "artist": item["artists"][0]["name"] if item.get("artists") else "Unknown",
                "album": album.get("name", "Unknown"),
                "release_date": album.get("release_date", ""),
                "image": album["images"][0]["url"] if album.get("images") else None,
            })

        return jsonify({"tracks": tracks, "query": query, "count": len(tracks)})

    except Exception:
        traceback.print_exc()
        return jsonify({
            "error": "search_error",
            "message": "Failed to search tracks"
        }), 500
