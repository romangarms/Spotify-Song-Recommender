"""
Generation API Blueprint

Handles playlist generation endpoints.
"""

import traceback
from flask import Blueprint, jsonify, request
from services.system_account import (
    parse_track_ids_from_text,
    get_tracks_by_ids,
    get_public_spotify,
    create_playlist_on_system_account,
    discard_playlist,
    SystemTokenExpiredError,
    SpotifyRateLimitedError,
    MAX_PASTED_TRACKS,
    SEARCH_MAX_LIMIT,
)
from services.logic_api import (
    generate_from_text,
    recommend_from_tracks,
    LogicGenerationError,
)
from utils.rate_limit import rate_limit_required

generation_bp = Blueprint("generation", __name__)

DECLINED_HINT = (
    "Try adding more songs, or some better-known ones, so the AI has more to "
    "work from."
)


def build_playlist(populate):
    """
    Create a draft playlist and hand it to populate(playlist_id).

    A failed generation would otherwise strand a "Work in Progress" playlist
    on the system account, so the draft is discarded before the error escapes.

    Args:
        populate: Callable taking the new playlist ID, returning the Logic
                  API result dict

    Returns:
        dict: JSON-serializable response describing the finished playlist
    """
    playlist_id = create_playlist_on_system_account(
        "GEN: Work in Progress",
        "Being generated by the Logic API",
    )

    try:
        result = populate(playlist_id)
    except Exception:
        discard_playlist(playlist_id)
        raise

    return {
        "playlist_id": playlist_id,
        "playlist_url": f"https://open.spotify.com/playlist/{playlist_id}",
        "title": result["title"],
        "description": result["description"],
        "tracks": result["tracks"],
        "not_found": result.get("not_found", []),
    }


